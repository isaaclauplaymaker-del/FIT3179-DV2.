function prepareCharts(year, grade, subject) {
    for (const spec of [chart3, chart4, chart7, chart11, chart13]) {
        spec.params.find(p => p.name === "focus_state").value = selectedState;
    }
    // Chart 1: all year levels and both subjects.

    replaceRows(
        nationalData,
        grades.flatMap(g =>
            subjects.map(s => ({
                gradeLabel: "Year " + g,
                domain: s,
                support: block(year, g, s).national[0],
                label: block(year, g, s).national[0].toFixed(1) + "%"
            }))
        )
    );

    // Chart 2: selected year level, both subjects.

    const categories = [
        "Needs additional support",
        "Developing",
        "Strong",
        "Exceeding",
        "Exempt"
    ];

    replaceRows(
        proficiencyData,
        subjects.flatMap(s =>
            categories.map((category, i) => ({
                subject: s,
                category: category,
                percentage: block(year, grade, s).national[i],
                order: i + 1
            }))
        )
    );

    // Charts 3 and 4: update state results.

    for (let i = 0; i < stateData.length; i++) {
        for (const s of subjects) {
            const a = block(year, grade, s).states[i];
            const prefix = s.toLowerCase();

            stateData[i][prefix + "_support"] = a[0];
            stateData[i][prefix + "_participants"] = a[1];
            stateData[i][prefix + "_participation"] = a[2];
            stateData[i][prefix + "_flag"] = a[3];
        }
    }

    // Chart 7: missing achievement stays missing.

    replaceRows(
        stateSupportData,
        stateData.flatMap(d =>
            subjects.map(s => ({
                state: d.state,
                domain: s,
                support: d[s.toLowerCase() + "_support"]
            }))
        ).filter(d => d.support !== null)
    );

    // Chart 8: remoteness.

    replaceRows(
        remotenessData,
        subjects.flatMap(s =>
            remoteNames.map((subgroup, i) => ({
                domain: s,
                subgroup: subgroup,
                support: block(year, grade, s).remote[i]
            }))
        )
    );

    // Chart 9: all year levels.

    replaceRows(
        genderData,
        grades.flatMap(g =>
            subjects.map(s => ({
                grade: "Year " + g,
                domain: s,
                gap: block(year, g, s).gap
            }))
        )
    );

    // Chart 10: parental-education category profiles.

    replaceRows(
        parentData,
        subjects.flatMap(s =>
            parentNames.flatMap((parent, i) =>
                dimensions.map((dimension, axis) => ({
                    domain: s,
                    parent: parent,
                    dimension: dimension,
                    axis: axis,
                    value: block(year, grade, s).parents[i][axis]
                }))
            )
        )
    );

    chart3.params[0].value = subject;
    chart4.params[0].value = subject;
    chart10.params[0].value = subject;

    chart2.title =
        "Year " + grade + " proficiency, Australia, " + year;

    // Chart 11: selected participation and national reference.

    chart11.data.values = stateData.map((d, i) => ({
        state: d.state,
        participation: block(year, grade, subject).states[i][2],
        national: block(year, grade, subject).national[6]
    }));

    // Chart 12: fixed 2023–2026 window, selected year level.

    chart12.data.values = years.flatMap(y =>
        subjects.map(s => ({
            year: y,
            subject: s,
            support: block(y, grade, s).national[0]
        }))
    );

    // Chart 13: same seven jurisdictions in every year.

    chart13.data.values = years.flatMap(y =>
        stateData.flatMap((d, i) =>
            d.abbr === "TAS"
                ? []
                : [{
                    year: y,
                    state: d.state,
                    abbr: d.abbr,
                    support: block(y, grade, subject).states[i][0],
                    flag: block(y, grade, subject).states[i][3]
                }]
        )
    );

    // Chart 14: baseline 2023 versus selected year.
    // Selecting 2023 shows the baseline points only.

    chart14.data.values = [...new Set([2023, year])].flatMap(y => [
        {
            year: y,
            parent: "Year 11 or below",
            proficient: block(y, grade, subject).ends[0]
        },
        {
            year: y,
            parent: "Bachelor or above",
            proficient: block(y, grade, subject).ends[1]
        }
    ]);
}

